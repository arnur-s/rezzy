/**
 * Generates the readable-size floor for font sizes that live inside Astryx.
 *
 * Astryx compiles its styles with StyleX, so every declaration is an atomic
 * class with a hashed name (`.x1k6wstc { font-size: 10px }`). Those hashes are
 * an output of the dependency's build, not part of its public API: they change
 * whenever the declaration list changes, and nothing warns us when they do.
 * Naming them by hand in `src/styles.css` was a rule that silently stopped
 * matching anything on the next upgrade.
 *
 * So the hashes are derived instead. This reads the `astryx.css` that is
 * actually installed, finds every class whose `font-size` cannot clear the
 * floor on its own, and writes the overrides to a generated stylesheet. An
 * upgrade that renames the hash produces a different generated file rather than
 * a rule that matches nothing.
 *
 * Two kinds of declaration qualify:
 *
 *   - a literal below the floor (`font-size: 10px`), which no theme token can
 *     reach, and
 *   - a size computed per instance into an inline custom property
 *     (`font-size: var(--x-fontSize)`, which `Avatar` sets to `size * 0.4`),
 *     which no static value can reach either.
 *
 * Sizes that resolve through a theme token are left alone: `gothicTheme.ts`
 * clamps that scale, and overriding them here would fight the theme.
 *
 * Usage:
 *   node scripts/font-floor-build.mjs          # write the stylesheet
 *   node scripts/font-floor-build.mjs --check  # fail if it is out of date
 */
import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'
import fs from 'node:fs'
import path from 'node:path'
import process from 'node:process'

const require = createRequire(import.meta.url)
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')

/**
 * The floor, in px. Keep in sync with `FLOOR` in `scripts/font-size-check.mjs`,
 * which asserts the rendered result of this file.
 */
export const FLOOR_PX = 12

/** Where the generated stylesheet lands, relative to the repository root. */
export const OUTPUT_PATH = 'src/generated/astryx-font-floor.css'

/**
 * Custom properties Astryx writes inline per instance, so their value is
 * unknowable at build time and can be below the floor.
 */
const DYNAMIC_FONT_SIZE_VARS = new Set(['--x-fontSize'])

/** `10px`, `0.75rem`, `12px` … in px. Returns null for anything non-literal. */
function literalToPx(value) {
  const match = /^(-?[\d.]+)(px|rem|em)$/.exec(value.trim())
  if (!match) return null
  const amount = Number(match[1])
  if (!Number.isFinite(amount)) return null
  // rem/em against the 16px root; Astryx sets no root font-size of its own.
  return match[2] === 'px' ? amount : amount * 16
}

/**
 * Every StyleX atomic class in `css` that declares a `font-size` we may need to
 * raise, as `{ className, value, reason }`.
 */
export function findFloorCandidates(css) {
  // StyleX emits `.hash:not(#\#):not(#\#):not(#\#){font-size:VALUE}`; the
  // specificity hack is optional in older output, so it is matched loosely.
  const rule = /\.([A-Za-z0-9_-]+)(?::not\([^)]*\))*\s*\{\s*font-size\s*:\s*([^;}]+)/g
  const found = new Map()

  for (const match of css.matchAll(rule)) {
    const [, className, rawValue] = match
    const value = rawValue.trim()

    const px = literalToPx(value)
    if (px != null) {
      if (px < FLOOR_PX) {
        found.set(className, { className, value, reason: 'literal' })
      }
      continue
    }

    const varMatch = /^var\(\s*(--[A-Za-z0-9_-]+)\s*\)$/.exec(value)
    if (varMatch && DYNAMIC_FONT_SIZE_VARS.has(varMatch[1])) {
      found.set(className, { className, value, reason: 'inline-dynamic' })
    }
  }

  return [...found.values()].sort((a, b) => a.className.localeCompare(b.className))
}

const REASON_NOTE = {
  literal: 'a literal size in astryx.css, unreachable from the theme scale',
  'inline-dynamic':
    'computed per instance into an inline custom property (e.g. Avatar initials at size * 0.4)',
}

/** The generated stylesheet for `candidates`. */
export function renderStylesheet(candidates, { version }) {
  const header = [
    '/*',
    ' * Generated by scripts/font-floor-build.mjs. Do not edit.',
    ' *',
    ` * Raises every Astryx font-size that cannot reach the ${FLOOR_PX}px readable`,
    ' * floor on its own. The selectors are StyleX atomic hashes, so they are read',
    ' * out of the installed package rather than written by hand: run',
    ' * `pnpm astryx:font-floor` after upgrading @astryxdesign/core.',
    ' *',
    ` * Source: @astryxdesign/core@${version}`,
    ' *',
    ' * `max()` keeps this a floor rather than an override, so a large avatar keeps',
    ' * its proportional initials and only the sizes below the floor are raised.',
    ' */',
    '',
  ].join('\n')

  if (candidates.length === 0) {
    return `${header}/* No Astryx font-size falls below the floor in this version. */\n`
  }

  const floorRem = `${FLOOR_PX / 16}rem`
  const body = candidates
    .map(
      ({ className, value, reason }) =>
        `  /* font-size: ${value} — ${REASON_NOTE[reason]} */\n` +
        `  .${className} {\n` +
        `    font-size: max(${floorRem}, ${value});\n` +
        `  }`,
    )
    .join('\n\n')

  // `components` sits above `astryx-base` in the layer order declared by
  // styles.css, so a single-class selector here still wins against Astryx's
  // own triple-`:not()` specificity hack.
  return `${header}@layer components {\n${body}\n}\n`
}

function build() {
  const cssPath = require.resolve('@astryxdesign/core/astryx.css')
  // The package does not export `./package.json`, so the manifest is read
  // relative to the resolved stylesheet (`<pkg>/dist/astryx.css`).
  const pkgPath = path.join(path.dirname(cssPath), '..', 'package.json')
  const version = JSON.parse(fs.readFileSync(pkgPath, 'utf8')).version
  const candidates = findFloorCandidates(fs.readFileSync(cssPath, 'utf8'))
  return { contents: renderStylesheet(candidates, { version }), candidates }
}

const isMain =
  process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)

if (isMain) {
  const outFile = path.join(ROOT, OUTPUT_PATH)
  const { contents, candidates } = build()
  const current = fs.existsSync(outFile) ? fs.readFileSync(outFile, 'utf8') : null

  if (process.argv.includes('--check')) {
    if (current !== contents) {
      console.error(
        `${OUTPUT_PATH} is out of date with the installed @astryxdesign/core.\n` +
          'Run `pnpm astryx:font-floor` and commit the result.',
      )
      process.exit(1)
    }
    console.log(`${OUTPUT_PATH} matches the installed Astryx (${candidates.length} rule(s)).`)
  } else if (current === contents) {
    console.log(`${OUTPUT_PATH} already up to date (${candidates.length} rule(s)).`)
  } else {
    fs.mkdirSync(path.dirname(outFile), { recursive: true })
    fs.writeFileSync(outFile, contents)
    console.log(`Wrote ${OUTPUT_PATH} (${candidates.length} rule(s)).`)
  }
}
