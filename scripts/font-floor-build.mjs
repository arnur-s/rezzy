import { dirname, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { readFile, writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
const root = dirname(dirname(fileURLToPath(import.meta.url)))

/** Read dependency output, never copy its private StyleX class names by hand. */
export function buildFontFloor(css, version) {
  const rules = new Map()
  let fontDeclarations = 0
  for (const [, selector, declarations] of css.matchAll(
    /([^{}]+)\{([^{}]+)\}/g,
  )) {
    const fontSize = declarations
      .match(/(?:^|;)\s*font-size\s*:\s*([^;}]+)/)?.[1]
      .trim()
    if (!fontSize) continue
    fontDeclarations += 1
    const literal = fontSize.match(/^(\d*\.?\d+)(px|rem)$/)
    const isComputed = fontSize === 'var(--x-fontSize)'
    const belowFloor =
      literal && Number(literal[1]) * (literal[2] === 'rem' ? 16 : 1) < 12
    if (!isComputed && !belowFloor) {
      if (
        !literal &&
        !/^(inherit|var\(--(?:font-size-|text-|spacing-)[\w-]+\)|max\(1rem,\s*var\(--text-[\w-]+\)\))$/.test(
          fontSize,
        )
      ) {
        throw new Error(
          `Review new Astryx font-size expression before generating: ${fontSize}`,
        )
      }
      continue
    }
    const atomicSelector = selector.trim()
    // A conditional or compound selector needs review, rather than silently
    // broadening a dependency rule into a global override.
    if (!/^\.[\w-]+(?::not\(#\\#\))*$/.test(atomicSelector)) {
      throw new Error(
        `Review new Astryx font-floor selector: ${atomicSelector}`,
      )
    }
    rules.set(atomicSelector, fontSize)
  }
  if (!fontDeclarations)
    throw new Error(
      'No Astryx font-size declarations found; review the dependency CSS format.',
    )
  return `/* Generated by scripts/font-floor-build.mjs. Do not edit.
 * Source: @astryxdesign/core@${version}
 * Run pnpm astryx:font-floor after dependency upgrades.
 * Theme tokens own the type scale; these rules cover literal/computed sizes.
 */
@layer components {
${[...rules]
  .sort(([left], [right]) => left.localeCompare(right))
  .map(
    ([selector, size]) => `  ${selector} {
    font-size: max(0.75rem, ${size});
  }`,
  )
  .join('\n\n')}
}
`
}

export async function checkFontFloor() {
  const cssPath = require.resolve('@astryxdesign/core/astryx.css')
  const pkg = JSON.parse(
    await readFile(resolve(dirname(cssPath), '../package.json'), 'utf8'),
  )
  const output = buildFontFloor(await readFile(cssPath, 'utf8'), pkg.version)
  const target = resolve(root, 'src/generated/astryx-font-floor.css')
  if (process.argv.includes('--check')) {
    const existing = await readFile(target, 'utf8').catch(() => '')
    if (existing.replaceAll('\r\n', '\n') !== output) {
      throw new Error(
        'Astryx font-floor CSS is stale. Run pnpm astryx:font-floor and commit the result.',
      )
    }
  } else {
    await writeFile(target, output)
  }
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(resolve(process.argv[1])).href
) {
  await checkFontFloor()
}
